  } catch {
    podPermission.value = { canCreate: false }
  }

  if (!canCreatePods.value && activeTab.value === 'create') {
    activeTab.value = 'active'
  }
}

function switchTab(tab) {
  if (tab === 'create' && !canCreatePods.value) return
  activeTab.value = tab
  createError.value = ''
  conflicts.value = []
  clearPodFilters()
}

async function createPod() {
  if (!canSubmitPod.value || creating.value) return

  creating.value = true
  createError.value = ''
  conflicts.value = []

  try {
    const data = await apiRequest('/modules/team-tracker/pods', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name: podName.value.trim(),
        memberUids: selectedPeople.value.map(person => person.uid),
        focusKeys: parseFocusKeys(focusKeysInput.value)
      })
    })

    createdPodNotice.value = {
      name: data.pod.name,
      memberCount: data.pod.memberCount
    }

    selectedUids.value = []
    podName.value = POD_PREVIEW_NAME
    focusKeysInput.value = ''
    await loadPods()
    activeTab.value = 'active'
  } catch (err) {
    conflicts.value = err.data?.details?.conflicts || []
    createError.value = err.message || 'Failed to create pod'
  } finally {
    creating.value = false
  }
}

function openCompleteAction(pod) {
  podAction.value = { type: 'complete', pod }
  actionName.value = ''
  actionFocusKeys.value = ''
  actionError.value = ''
}

function openNextOutcomeAction(pod) {
  podAction.value = { type: 'next', pod }
  actionName.value = `${pod.name} — Next outcome`
  actionFocusKeys.value = ''
  actionError.value = ''
}

function closePodAction() {
  if (actionBusy.value) return
  podAction.value = null
  actionError.value = ''
}

async function confirmPodAction() {
  if (!podAction.value || actionBusy.value) return

  const { type, pod } = podAction.value
  actionBusy.value = true
  actionError.value = ''

  try {
    if (type === 'complete') {
      await apiRequest(`/modules/team-tracker/pods/${pod.id}/archive`, { method: 'POST' })
      activeTab.value = 'archived'
    } else {
      const name = actionName.value.trim()
      if (!name) throw new Error('Enter a name for the next outcome')

      const data = await apiRequest(`/modules/team-tracker/pods/${pod.id}/next-outcome`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          name,
          focusKeys: parseFocusKeys(actionFocusKeys.value)
        })
      })

      createdPodNotice.value = {
        name: data.pod.name,
        memberCount: data.pod.memberCount
      }
      activeTab.value = 'active'
    }

    podAction.value = null
    await loadPods()
  } catch (err) {
    actionError.value = err.message || 'Pod action failed'
  } finally {
    actionBusy.value = false
  }
}

function parseFocusKeys(value) {
  return String(value || '')
    .split(',')
    .map(key => key.trim())
    .filter(Boolean)
}

function podFocusKeys(pod) {
  return Array.isArray(pod.focusKeys) ? pod.focusKeys : []
}

function focusUrl(key) {
  return `https://redhat.atlassian.net/browse/${encodeURIComponent(key)}`
}

function formatDate(value) {
  if (!value) return ''
  return new Date(value).toLocaleString()
}

function bubbleStyle(uid) {
  let hash = 0
  for (let i = 0; i < uid.length; i++) {
    hash = (hash * 31 + uid.charCodeAt(i)) >>> 0
  }
  return { backgroundImage: BUBBLE_GRADIENTS[hash % BUBBLE_GRADIENTS.length] }
}

function personFieldValue(p, fieldId) {
  const val = (p._appFields || {})[fieldId]
  if (Array.isArray(val)) return val.join(', ')
  return val || ''
}

function personTeamList(p) {
  if ((p.orgType || 'engineering') === 'auxiliary') {
    return p.associatedTeamNames || []
  }
  return p.teams || []
}

function personTeamDisplay(p) {
  return personTeamList(p).join(', ')
}

function toggleSort(field) {
  if (sortField.value === field) {
    sortAsc.value = !sortAsc.value
  } else {
    sortField.value = field
    sortAsc.value = true
  }
}

function sortIcon(field) {
  if (sortField.value !== field) return ''
  return sortAsc.value ? ' \u25B2' : ' \u25BC'
}

function openPerson(uid) {
  nav.navigateTo('person-detail', { uid })
}


function exportCsv() {
  const fieldLabels = personFieldDefs.value.map(fd => fd.label)
  const rows = [['Org', 'Name', 'UID', 'Email', 'Title', 'Geo', 'Location', 'Team(s)', 'GitHub', 'GitLab', 'Type', ...fieldLabels]]
  for (const p of filtered.value) {
    const fieldValues = personFieldDefs.value.map(fd => personFieldValue(p, fd.id))
    rows.push([
      p.orgDisplayName || '', p.name, p.uid, p.email, p.title, p.geo || '',
      p.location || '', personTeamDisplay(p),
      p.github ? p.github.username : '', p.gitlab ? p.gitlab.username : '',
      p.orgType || 'engineering', ...fieldValues
    ])
  }
  const csv = rows.map(r => r.map(c => '"' + String(c).replace(/"/g, '""') + '"').join(',')).join('\n')
  const blob = new Blob([csv], { type: 'text/csv' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = 'people-' + new Date().toISOString().slice(0, 10) + '.csv'
  a.click()
  URL.revokeObjectURL(url)
}

