function formatMirrorTimestamp(value) {
  if (!value) return 'unknown'
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return 'unknown'
  return date.toLocaleString(undefined, {
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  })
}

function freezeLabel(pod) {
  const mirror = podMirror(pod)
  const days = mirror && mirror.attention ? mirror.attention.daysToFreeze : null
  if (days === null || days === undefined) return ''
  return days < 0 ? `${Math.abs(days)}d past freeze` : `${days}d to freeze`
}

