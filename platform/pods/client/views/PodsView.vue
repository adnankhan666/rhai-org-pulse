async function loadPodMirrors(pods) {
  const active = (pods || []).filter(pod => pod.status === 'active')
  mirrorsError.value = false
  if (active.length === 0) {
    podMirrors.value = {}
    mirrorsLoading.value = false
    return
  }

  mirrorsLoading.value = true
  try {
    const data = await apiRequest('/modules/team-tracker/pods/mirrors', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ podIds: active.map(pod => pod.id) })
    })
    podMirrors.value = data.mirrors || {}
  } catch {
    podMirrors.value = {}
    mirrorsError.value = true
  } finally {
    mirrorsLoading.value = false
  }
}

function podMirror(pod) {
  if (!pod || pod.status !== 'active') return null
  return podMirrors.value[pod.id] || null
}

function mirrorProgressPct(pod) {
  const mirror = podMirror(pod)
  if (mirror && mirror.progress && mirror.progress.pct !== null) return mirror.progress.pct
  return podProgressPct(pod)
}

function mirrorProgressLabel(pod) {
  const mirror = podMirror(pod)
  if (!mirror || !mirror.progress || mirror.progress.pct === null) return ''
  return `${mirror.progress.done}/${mirror.progress.total}`
}

function progressSegments(pod) {
  const mirror = podMirror(pod)
  const progress = mirror && mirror.progress
  if (!progress || !progress.total) return null
  const total = progress.total
  return [
    { key: 'Done', count: progress.done, cls: 'bg-emerald-500' },
    { key: 'In progress', count: progress.inProgress, cls: 'bg-amber-400' },
    { key: 'To do', count: progress.todo, cls: 'bg-gray-300 dark:bg-gray-600' },
    { key: 'Other', count: progress.other, cls: 'bg-gray-400' }
  ].filter(segment => segment.count > 0).map(segment => ({
    ...segment,
    pct: (segment.count / total) * 100,
    label: `${segment.key}: ${segment.count}`
  }))
}

function mirrorProgressText(pod) {
  const fraction = mirrorProgressLabel(pod)
  if (fraction) return `${mirrorProgressPct(pod)}% · ${fraction}`
  return `${mirrorProgressPct(pod)}% complete`
}

function mirrorProgressTitle(pod) {
  const fraction = mirrorProgressLabel(pod)
