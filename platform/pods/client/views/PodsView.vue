function isBlockedStatus(status) {
  return /block|impediment/i.test(String(status || ''))
}

/**
 * Signal drives the pill colour, not the raw status category.
 * In progress + on track is healthy, so it reads green.
 */
function podSignal(pod) {
  if (pod.status === 'archived') return 'archived'
  const mirror = podMirror(pod)
  if (!mirror) return 'active'
  if (isBlockedStatus(mirror.status)) return 'blocked'
  const state = mirror.attention && mirror.attention.state
  if (state === 'overdue') return 'overdue'
  if (state === 'behind') return 'behind'
  if (state === 'delivered') return 'delivered'
  if (mirror.statusCategory === 'To Do') return 'todo'
  if (state === 'on_track') return 'on_track'
  return 'in_progress'
}

